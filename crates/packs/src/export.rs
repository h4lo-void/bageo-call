//! packs export-app: turns the app.json and desktop.json of every language
//! that is ready into the phone app's string resources
//! (values-<qualifier>/strings.xml and xml/locales_config.xml) and the
//! desktop widget's i18n.ext.json.
//!
//! A language is ready for a file when its names pass and at least
//! [READY_PERCENT] percent of that file's English keys pass the rules; keys
//! that break a rule or that a reviewer marked needs_fix are left out (the
//! app shows the English line).

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use crate::locales::{
    check_loc_file, check_names, drop_needs_fix, ext_lang, locfile_of, names_of, printf_spec_len, printf_tokens, Ctx, Kind, LocaleSources,
    READY_PERCENT,
};
use crate::Issue;

/// Every file this tool writes says so on its first lines.
pub const GENERATED_MARK: &str = "Generated by packs export-app";

/// The app languages kept by hand in bageo-call (values, values-de, ...).
pub const CORE_APP_LOCALES: [&str; 9] = ["en", "de", "es", "fr", "ja", "ko", "pt", "zh-CN", "zh-TW"];

/// What export-app would write.
#[derive(Debug, Clone, Default)]
pub struct AppExport {
    /// Path under the Android res folder to file content.
    pub android: BTreeMap<String, String>,
    /// i18n.ext.json.
    pub desktop: String,
    /// Languages written for Android.
    pub langs: Vec<String>,
    /// Keys and languages left out, and why.
    pub issues: Vec<Issue>,
}

/// The values folder Android reads for a language: the old codes it still
/// expects (in, iw, ji) and the b+ form for three-letter codes.
pub fn android_qualifier(code: &str) -> String {
    let legacy = match code {
        "id" => "in",
        "he" => "iw",
        "yi" => "ji",
        c => c,
    };
    if legacy.len() == 2 {
        format!("values-{legacy}")
    } else {
        format!("values-b+{legacy}")
    }
}

/// A string as Android resource text: XML escapes, backslash before quotes,
/// apostrophes and a leading @ or ?, and (in a string with format
/// arguments) a lone % doubled. In a string without format arguments a %
/// stays as written; [strings_xml] marks that string formatted="false" so
/// Android never reads "50% di" as a format.
pub fn android_escape(s: &str, formatted: bool) -> String {
    let c: Vec<char> = s.chars().collect();
    let mut out = String::with_capacity(s.len() + 8);
    let mut i = 0;
    while i < c.len() {
        match c[i] {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            x @ ('@' | '?') if i == 0 => {
                out.push('\\');
                out.push(x);
            }
            '%' if formatted => match printf_spec_len(&c[i..]) {
                Some(n) => {
                    out.extend(&c[i..i + n]);
                    i += n;
                    continue;
                }
                None => out.push_str("%%"),
            },
            x => out.push(x),
        }
        i += 1;
    }
    out
}

/// A value for an XML attribute in double quotes. Keys are checked long
/// before they get here ([crate::locales::valid_key]); this is the second
/// fence.
pub fn xml_attr(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&apos;"),
            c if c.is_control() => out.push_str(&format!("&#x{:X};", c as u32)),
            c => out.push(c),
        }
    }
    out
}

fn header(commit: Option<&str>) -> String {
    let from = commit.map(|c| format!("bageo-packs {c}")).unwrap_or_else(|| "bageo-packs".to_string());
    format!("<!-- {GENERATED_MARK} from {from}. Do not edit by hand; change the translation in bageo-packs. -->")
}

fn strings_xml(tr: &BTreeMap<String, String>, en: &BTreeMap<String, String>, commit: Option<&str>) -> String {
    let mut s = String::from("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
    s.push_str(&header(commit));
    s.push_str("\n<resources>\n");
    for (k, v) in tr {
        let formatted = en.get(k).is_some_and(|e| !printf_tokens(e).is_empty());
        let literal = if !formatted && v.contains('%') { " formatted=\"false\"" } else { "" };
        s.push_str(&format!("    <string name=\"{}\"{literal}>{}</string>\n", xml_attr(k), android_escape(v, formatted)));
    }
    s.push_str("</resources>\n");
    s
}

fn locales_config(langs: &BTreeSet<String>, commit: Option<&str>) -> String {
    let mut s = String::from("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
    s.push_str(&header(commit));
    s.push_str("\n<locale-config xmlns:android=\"http://schemas.android.com/apk/res/android\">\n");
    for t in CORE_APP_LOCALES.iter().copied().chain(langs.iter().map(String::as_str)) {
        s.push_str(&format!("    <locale android:name=\"{t}\"/>\n"));
    }
    s.push_str("</locale-config>\n");
    s
}

/// Works out the files for every ready language. commit is the packs commit
/// named in the Android file headers.
pub fn export_app(ls: &LocaleSources, commit: Option<&str>) -> AppExport {
    let mut issues = Vec::new();
    let mut android = BTreeMap::new();
    let mut desktop: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    let mut langs = BTreeSet::new();
    for l in &ls.langs {
        let Ok(info) = ext_lang(&l.code) else { continue };
        let Some(n) = &l.names else { continue };
        let mut bad = Vec::new();
        check_names(&mut bad, &n.file, "", &l.code, info, &names_of(&n.data));
        if !bad.is_empty() {
            issues.extend(bad);
            continue;
        }
        for kind in [Kind::App, Kind::Desktop] {
            let (Some(sf), Some(en)) = (l.files.get(&kind), ls.english.files.get(&kind)) else { continue };
            if sf.data.lang != l.code {
                continue;
            }
            let cx = Ctx { file: &sf.file, prefix: "", kind, info, strict: false };
            let mut f = check_loc_file(&mut issues, &cx, &locfile_of(&sf.data), en);
            drop_needs_fix(l, kind, &mut f);
            let total = en.text.strings.len();
            if total == 0 || f.strings.len() * 100 < READY_PERCENT * total {
                continue;
            }
            let strings: BTreeMap<String, String> =
                f.strings.iter().filter_map(|(k, v)| v.as_str().map(|s| (k.clone(), s.to_string()))).collect();
            if kind == Kind::App {
                android.insert(format!("{}/strings.xml", android_qualifier(&l.code)), strings_xml(&strings, &en.text.strings, commit));
                langs.insert(l.code.clone());
            } else {
                desktop.insert(l.code.clone(), strings);
            }
        }
    }
    android.insert("xml/locales_config.xml".to_string(), locales_config(&langs, commit));
    let desktop = serde_json::to_string_pretty(&desktop).unwrap_or_else(|_| "{}".to_string()) + "\n";
    AppExport { android, desktop, langs: langs.into_iter().collect(), issues }
}

/// Writes the export (check = false) or only compares it (check = true).
/// Returns the files that differ: missing, changed, or generated earlier for
/// a language that is no longer exported (those are removed when writing).
pub fn apply_app_export(e: &AppExport, res: &Path, desktop: &Path, check: bool) -> io::Result<Vec<String>> {
    let mut changed = Vec::new();
    let mut wanted: BTreeSet<PathBuf> = BTreeSet::new();
    for (rel, body) in &e.android {
        let p = res.join(rel);
        wanted.insert(p.clone());
        if fs::read_to_string(&p).ok().as_deref() != Some(body.as_str()) {
            changed.push(p.display().to_string());
            if !check {
                if let Some(d) = p.parent() {
                    fs::create_dir_all(d)?;
                }
                fs::write(&p, body)?;
            }
        }
    }
    if let Ok(rd) = fs::read_dir(res) {
        let mut dirs: Vec<PathBuf> = rd.filter_map(|d| d.ok().map(|d| d.path())).collect();
        dirs.sort();
        for d in dirs {
            let is_values = d.file_name().and_then(|n| n.to_str()).is_some_and(|n| n.starts_with("values-"));
            let p = d.join("strings.xml");
            if !is_values || wanted.contains(&p) {
                continue;
            }
            if fs::read_to_string(&p).is_ok_and(|t| t.contains(GENERATED_MARK)) {
                changed.push(format!("{} (no longer exported)", p.display()));
                if !check {
                    fs::remove_file(&p)?;
                    let _ = fs::remove_dir(&d);
                }
            }
        }
    }
    if fs::read_to_string(desktop).ok().as_deref() != Some(e.desktop.as_str()) {
        changed.push(desktop.display().to_string());
        if !check {
            if let Some(d) = desktop.parent() {
                fs::create_dir_all(d)?;
            }
            fs::write(desktop, &e.desktop)?;
        }
    }
    Ok(changed)
}
